func main() {
	if len(os.Args) < 2 || os.Args[1] == "" {
		panic("root directory is required to be given as argument")
	}
	rootDir := os.Args[1]
	absRootDir, err := filepath.Abs(rootDir)
	if err != nil {
		panic(fmt.Sprintf("cannot calculate the absolute path with %s", rootDir))
	}
	if len(os.Args) > 2 && os.Args[2] == "runtime-schemes" {
		if err := generateServiceAPISchemePackages(absRootDir); err != nil {
			panic(fmt.Sprintf("cannot generate service-scoped API schemes: %v", err))
		}
		return
	}
	templates.ControllerTemplate = controllerTemplateWithManagedMetricRecorder(templates.ControllerTemplate)
	pipeline.Run(config.GetProviderForGeneration(), config.GetProviderNamespacedForGeneration(), absRootDir)
	if err := generateServiceControllerSetupPackages(absRootDir); err != nil {
		panic(fmt.Sprintf("cannot generate service-scoped controller setup packages: %v", err))
	}
	if err := generateRuntimeTerraformResourceManifest(absRootDir); err != nil {
		panic(fmt.Sprintf("cannot generate runtime Terraform resource manifest: %v", err))
	}
	if err := generateProviderConfigMain(absRootDir); err != nil {
		panic(fmt.Sprintf("cannot generate lightweight ProviderConfig main: %v", err))
	}
}

var managedResourceReferencePattern = regexp.MustCompile(`GetManagedResource\("([^"]+)", "([^"]+)"`)

type apiPackage struct {
	scope   string
	service string
	version string
}

func generateServiceAPISchemePackages(rootDir string) error {
	setupFiles, err := filepath.Glob(filepath.Join(rootDir, "internal", "controller", "cluster", "zz_*_setup.go"))
	if err != nil {
		return fmt.Errorf("cannot find generated service setup files: %w", err)
	}
	for _, setupFile := range setupFiles {
		service := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(setupFile), "zz_"), "_setup.go")
		if service == "config" || service == "monolith" {
			continue
		}

		packages := map[apiPackage]struct{}{
			{scope: "cluster", service: service, version: "v1alpha1"}:    {},
			{scope: "namespaced", service: service, version: "v1alpha1"}: {},
			{scope: "cluster", version: "v1beta1"}:                       {},
			{scope: "namespaced", version: "v1beta1"}:                    {},
		}
		for _, scope := range []string{"cluster", "namespaced"} {
			resolverPath := filepath.Join(rootDir, "apis", scope, service, "v1alpha1", "zz_generated.resolvers.go")
			content, err := os.ReadFile(resolverPath)
			if os.IsNotExist(err) {
				continue
			}
			if err != nil {
				return fmt.Errorf("cannot read %s resolver references: %w", service, err)
			}
			for _, match := range managedResourceReferencePattern.FindAllSubmatch(content, -1) {
				pkg, err := apiPackageForGroup(string(match[1]), string(match[2]))
				if err != nil {
					return fmt.Errorf("cannot map %s API reference in %s: %w", match[1], resolverPath, err)
				}
				packages[pkg] = struct{}{}
			}
		}
		if err := writeServiceAPIScheme(rootDir, service, packages); err != nil {
			return err
		}
	}
	return nil
}

func apiPackageForGroup(group, version string) (apiPackage, error) {
	const (
		clusterSuffix    = ".oci.upbound.io"
		namespacedSuffix = ".oci.m.upbound.io"
	)
	scope := "cluster"
	suffix := clusterSuffix
	if strings.HasSuffix(group, namespacedSuffix) {
		scope, suffix = "namespaced", namespacedSuffix
	} else if !strings.HasSuffix(group, clusterSuffix) {
		return apiPackage{}, fmt.Errorf("unsupported API group %q", group)
	}
	service := strings.TrimSuffix(group, suffix)
	if service == "" || strings.Contains(service, ".") {
		return apiPackage{}, fmt.Errorf("cannot determine service from API group %q", group)
	}
	return apiPackage{scope: scope, service: service, version: version}, nil
}

func writeServiceAPIScheme(rootDir, service string, packages map[apiPackage]struct{}) error {
	ordered := make([]apiPackage, 0, len(packages))
	for pkg := range packages {
		apiDir := filepath.Join(rootDir, "apis", pkg.scope)
		if pkg.service != "" {
			apiDir = filepath.Join(apiDir, pkg.service)
		}
		if _, err := os.Stat(filepath.Join(apiDir, pkg.version)); err != nil {
			return fmt.Errorf("cannot find referenced API package for %s: %w", service, err)
		}
		ordered = append(ordered, pkg)
	}
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].scope != ordered[j].scope {
			return ordered[i].scope < ordered[j].scope
		}
		if ordered[i].service != ordered[j].service {
			return ordered[i].service < ordered[j].service
		}
		return ordered[i].version < ordered[j].version
	})

	var output strings.Builder
	output.WriteString("// Code generated by provider-oci. DO NOT EDIT.\n\npackage scheme\n\nimport (\n")
	output.WriteString("\t\"k8s.io/apimachinery/pkg/runtime\"\n")
	for i, pkg := range ordered {
		path := fmt.Sprintf("github.com/oracle/provider-oci/apis/%s", pkg.scope)
		if pkg.service != "" {
			path += "/" + pkg.service
		}
		fmt.Fprintf(&output, "\tapi%d %q\n", i, path+"/"+pkg.version)
	}
	output.WriteString(")\n\n// AddToSchemes registers only the API types needed by this service runtime.\n")
	output.WriteString("var AddToSchemes = runtime.SchemeBuilder{\n")
	for i := range ordered {
		fmt.Fprintf(&output, "\tapi%d.SchemeBuilder.AddToScheme,\n", i)
	}
	output.WriteString("}\n")

	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return fmt.Errorf("cannot format %s API scheme: %w", service, err)
	}
	targetDir := filepath.Join(rootDir, "internal", "apis", "runtime", service)
	if err := os.MkdirAll(targetDir, 0o755); err != nil {
		return fmt.Errorf("cannot create %s API scheme directory: %w", service, err)
	}
	return os.WriteFile(filepath.Join(targetDir, "zz_scheme.go"), formatted, 0o644)
}

// generateServiceControllerSetupPackages copies each generated service setup
// file into a package dedicated to that service. Importing the generated root
// controller package pulls every service controller into every provider binary,
// even when only one Setup_<service> function is called.
func generateServiceControllerSetupPackages(rootDir string) error {
	for _, scope := range []string{"cluster", "namespaced"} {
		controllerRoot := filepath.Join(rootDir, "internal", "controller", scope)
		matches, err := filepath.Glob(filepath.Join(controllerRoot, "zz_*_setup.go"))
		if err != nil {
			return fmt.Errorf("cannot find %s service setup files: %w", scope, err)
		}
		if len(matches) == 0 {
			return fmt.Errorf("no %s service setup files found under %s", scope, controllerRoot)
		}

		for _, sourcePath := range matches {
			name := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(sourcePath), "zz_"), "_setup.go")
			if name == "" {
				return fmt.Errorf("cannot determine service name from %s", sourcePath)
			}
			// The family provider has a dedicated lightweight main.
			if name == "config" {
				continue
			}
			targetDir := filepath.Join(controllerRoot, name)
			if name == "monolith" {
				if err := os.MkdirAll(targetDir, 0o755); err != nil {
					return fmt.Errorf("cannot create generated %s monolith controller directory: %w", scope, err)
				}
			}
			info, err := os.Stat(targetDir)
			if err != nil {
				return fmt.Errorf("cannot find generated %s controller directory for service %q: %w", scope, name, err)
			}
			if !info.IsDir() {
				return fmt.Errorf("generated %s controller path for service %q is not a directory", scope, name)
			}

			content, err := os.ReadFile(sourcePath)
			if err != nil {
				return fmt.Errorf("cannot read %s: %w", sourcePath, err)
			}
			if err := os.WriteFile(filepath.Join(targetDir, "zz_setup.go"), content, 0o644); err != nil {
				return fmt.Errorf("cannot write %s service setup package: %w", scope, err)
			}
		}
	}
	return nil
}

var terraformRuntimeResourcePattern = regexp.MustCompile(`o\.Provider\.Resources\["([^"]+)"\]`)

func generateRuntimeTerraformResourceManifest(rootDir string) error {
	controllerRoot := filepath.Join(rootDir, "internal", "controller", "cluster")
	resourcesByService := map[string]map[string]struct{}{}
	allResources := map[string]struct{}{}
	err := filepath.WalkDir(controllerRoot, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || entry.Name() != "zz_controller.go" {
			return nil
		}

		relativePath, err := filepath.Rel(controllerRoot, path)
		if err != nil {
			return err
		}
		parts := strings.Split(relativePath, string(filepath.Separator))
		if len(parts) < 3 {
			return fmt.Errorf("cannot determine provider service from controller path %s", path)
		}
		service := parts[0]

		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		matches := terraformRuntimeResourcePattern.FindAllSubmatch(content, -1)
		if len(matches) != 1 {
			return fmt.Errorf("%s contains %d Terraform provider resource lookups, want 1", path, len(matches))
		}
		resourceName := string(matches[0][1])
		if resourcesByService[service] == nil {
			resourcesByService[service] = map[string]struct{}{}
		}
		resourcesByService[service][resourceName] = struct{}{}
		allResources[resourceName] = struct{}{}
		return nil
	})
	if err != nil {
		return err
	}
	if len(resourcesByService) == 0 {
		return fmt.Errorf("no generated Terraform resource controllers found under %s", controllerRoot)
	}
	if err := validateNamespacedRuntimeTerraformResources(rootDir, resourcesByService); err != nil {
		return err
	}
	resourcesByService["monolith"] = allResources

	services := make([]string, 0, len(resourcesByService))
	for service := range resourcesByService {
		services = append(services, service)
	}
	sort.Strings(services)

	var output strings.Builder
	output.WriteString("// Code generated by provider-oci. DO NOT EDIT.\n\npackage config\n\n")
	output.WriteString("// runtimeTerraformResources maps generated provider service processes to the\n")
	output.WriteString("// Terraform resources whose controllers they run.\n")
	output.WriteString("var runtimeTerraformResources = map[string][]string{\n")
	for _, service := range services {
		resources := make([]string, 0, len(resourcesByService[service]))
		for resourceName := range resourcesByService[service] {
			resources = append(resources, resourceName)
		}
		sort.Strings(resources)
		fmt.Fprintf(&output, "\t%q: {\n", service)
		for _, resourceName := range resources {
			fmt.Fprintf(&output, "\t\t%q,\n", resourceName)
		}
		output.WriteString("\t},\n")
	}
	output.WriteString("}\n")

	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return fmt.Errorf("cannot format runtime Terraform resource manifest: %w", err)
	}
	return os.WriteFile(filepath.Join(rootDir, "config", "runtime_resources_generated.go"), formatted, 0o644)
}

func validateNamespacedRuntimeTerraformResources(rootDir string, clusterResources map[string]map[string]struct{}) error {
	controllerRoot := filepath.Join(rootDir, "internal", "controller", "namespaced")
	namespacedResources := map[string]map[string]struct{}{}
	err := filepath.WalkDir(controllerRoot, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || entry.Name() != "zz_controller.go" {
			return nil
		}

		relativePath, err := filepath.Rel(controllerRoot, path)
		if err != nil {
			return err
		}
		parts := strings.Split(relativePath, string(filepath.Separator))
		if len(parts) < 3 {
			return fmt.Errorf("cannot determine provider service from controller path %s", path)
		}
		service := parts[0]
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		matches := terraformRuntimeResourcePattern.FindAllSubmatch(content, -1)
		if len(matches) != 1 {
			return fmt.Errorf("%s contains %d Terraform provider resource lookups, want 1", path, len(matches))
		}
		if namespacedResources[service] == nil {
			namespacedResources[service] = map[string]struct{}{}
		}
		namespacedResources[service][string(matches[0][1])] = struct{}{}
		return nil
	})
	if err != nil {
		return err
	}

	for service, resources := range clusterResources {
		namespaced := namespacedResources[service]
		if len(namespaced) != len(resources) {
			return fmt.Errorf("service %q has %d cluster-scoped and %d namespaced Terraform resource controllers", service, len(resources), len(namespaced))
		}
		for resourceName := range resources {
			if _, ok := namespaced[resourceName]; !ok {
				return fmt.Errorf("service %q Terraform resource %q has no matching namespaced controller", service, resourceName)
			}
		}
		delete(namespacedResources, service)
	}
	if len(namespacedResources) != 0 {
		return fmt.Errorf("namespaced Terraform controller services have no cluster-scoped counterpart: %v", namespacedResources)
	}
	return nil
}

